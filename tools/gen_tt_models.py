"""Generate lib/tuya_thermostat/tt_models.c from the sources of tuya_thermostat_zrd.

    tools/gen_tt_models.py <tuya_thermostat_zrd>/src > lib/tuya_thermostat/tt_models.c

The tables (datapoint id, type, length, divisor, limits per logical field) are
read from the init_datapoint_modelN() functions and the numbers they use, so
nothing is copied by hand. The generated file is checked in; run this only when
the original changes.
"""

import re
import sys
from pathlib import Path

FIELDS = """ONOFF TEMP SETPOINT MIN MAX DEADZONE CALIBRATION RUNSTATE SENSOR PROG LOCKUNLOCK
SCHEDULE UNKNOWN TEMP_OUT FROST_PROTECT HEAT_PROTECT SCHEDULE_MON SCHEDULE_TUE SCHEDULE_WED
SCHEDULE_THU SCHEDULE_FRI SCHEDULE_SAT SCHEDULE_SUN LEVEL_A LEVEL_B ECO_MODE ECO_HEAT_TEMP
ECO_COOL_TEMP SOUND SETTINGS_RESET INVERSION THERM_MODE FAN_MODE FAN_CONTROL EXT_CALIBRATION
MODE_LOCK HUMIDITY HUMIDITY_OFFSET SCREEN_TIME LED_INDICATOR""".split()
# model files: suffix -> (README name, index into the manufacturer table)
MODELS = ["1", "2", "3", "4", "5", "6", "7", "8", "9", "0a", "0b", "0c", "0d"]
TYPES = {"DP_RAW": 0, "DP_BOOL": 1, "DP_VAL": 2, "DP_STR": 3, "DP_ENUM": 4, "DP_BITMAP": 5}


def parse_int(text, defines):
    text = text.strip()
    text = re.sub(r"//.*", "", text).strip()
    if text in defines:
        return defines[text]
    try:
        return int(text, 0)
    except ValueError:
        raise ValueError(f"cannot evaluate '{text}'")


def main():
    src = Path(sys.argv[1])
    header = (src / "include/app_tuya_datapoint.h").read_text()
    ids = {name: int(v, 16) for name, v in re.findall(r"(DP_TYPE\w+_ID_[0-9A-Fa-f]+)\s*=\s*0x([0-9A-Fa-f]+)", header)}
    ids["DP_TYPE0C_ID_00"] = 0
    defines = dict(ids)
    # "#define DP_TYPE5_ID_01 DP_TYPE2_ID_01": a model that reuses the ids of another
    aliases = dict(re.findall(r"#define\s+(DP_TYPE\w+_ID_[0-9A-Fa-f]+)\s+(DP_TYPE\w+_ID_[0-9A-Fa-f]+)", header))
    for _ in range(4):
        for name, target in aliases.items():
            if target in defines:
                defines[name] = defines[target]
    texts = {m: (src / f"app_thermostat_model{m}.c").read_text() for m in MODELS}
    for text in list(texts.values()) + [header]:
        for name, value in re.findall(r"#define\s+(R0?[0-9A-Da-d]+_\w+)\s+(-?(?:0x[0-9A-Fa-f]+|\d+))", text):
            defines[name] = int(value, 0)

    names_text = (src / "app_tuya_datapoint.c").read_text()
    products = {}
    for key, body in re.findall(r"tuya_manuf_name(\w+)\[\]\s*=\s*\{(.*?)NULL", names_text, re.S):
        products[key.lower()] = re.findall(r'"([^"]+)"', body)

    out = []
    out.append("/* SPDX-License-Identifier: Apache-2.0 */\n")
    out.append("/* Generated by tools/gen_tt_models.py from tuya_thermostat_zrd. Do not edit. */\n")
    out.append('#include <stdint.h>\n')
    out.append('#include <iot_drivers/tuya_thermostat.h>\n')
    out.append("#define DPT(i, t, l, d, lo, hi) {.id = (i), .type = (t), .len = (l), .divisor = (d), .min = (lo), .max = (hi)}\n")
    for m in MODELS:
        text = texts[m]
        # a model that reuses an index under another name: #define DP_IDX_SCHEDULE_MODE DP_IDX_SCHEDULE_MON
        renames = dict(re.findall(r"#define\s+DP_IDX_(\w+)\s+DP_IDX_(\w+)", text))
        rows = {}
        for idx, field, val in re.findall(r"data_point_model_common\[DP_IDX_(\w+)\]\.(\w+)\s*=\s*([^;]+);", text):
            rows.setdefault(renames.get(idx, idx), {})[field] = val.strip()
        out.append(f"static const struct iotdrv_tt_dp dp_model_{m}[IOTDRV_TT_FIELD_COUNT] = {{")
        for idx in FIELDS:
            d = rows.get(idx)
            if not d or "id" not in d:
                continue
            dp_id = parse_int(d["id"], defines)
            if dp_id == 0:
                continue
            dtype = TYPES.get(d.get("type", ""), 0xff)
            length = parse_int(d["len"], defines) if "len" in d else 0
            divisor = parse_int(d["divisor"], defines) if "divisor" in d else 0
            lo = parse_int(d["arg1"], defines) if "arg1" in d else "INT32_MIN"
            hi = parse_int(d["arg2"], defines) if "arg2" in d else "INT32_MAX"
            out.append(f"\t[IOTDRV_TT_F_{idx}] = DPT({dp_id:#04x}, {dtype}, {length}, {divisor}, {lo}, {hi}),")
        out.append("};\n")
    out.append("const struct iotdrv_tt_model iotdrv_tt_models[IOTDRV_TT_MODEL_COUNT] = {")
    for n, m in enumerate(MODELS):
        ids_c = ", ".join(f'"{p}"' for p in products[m])
        abs_min = parse_int(re.search(r"absMinHeatSetpointLimit\s*=\s*(\w+)", texts[m]).group(1), defines)
        abs_max = parse_int(re.search(r"absMaxHeatSetpointLimit\s*=\s*(\w+)", texts[m]).group(1), defines)
        out.append(f"\t[{n}] = {{.name = \"Tuya_Thermostat_r{m.upper().zfill(2)}\", "
                   f".products = (const char *const[]){{{ids_c}, NULL}}, .abs_min = {abs_min}, .abs_max = {abs_max}, "
                   f".dp = dp_model_{m}}},")
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
